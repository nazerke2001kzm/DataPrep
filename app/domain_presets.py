"""Пресеты промптов под тип модели / вида файла (обработка датасета)."""

from __future__ import annotations

from enum import Enum


class FilePreset(str, Enum):
    antifraud = "antifraud"
    legal_entity_scoring = "legal_entity_scoring"
    individual_scoring = "individual_scoring"
    credit_transition_matrix = "credit_transition_matrix"


PRESET_LABELS_RU: dict[str, str] = {
    FilePreset.antifraud.value: "Антифрод",
    FilePreset.legal_entity_scoring.value: "Скоринг юрлиц",
    FilePreset.individual_scoring.value: "Скоринг физлиц",
    FilePreset.credit_transition_matrix.value: "Матрица переходов",
}


def preset_domain_block(preset: FilePreset) -> str:
    """Фрагмент, добавляемый к базовому промпту планировщика."""

    blocks = {
        FilePreset.antifraud: """
КОНТЕКСТ ПРЕСЕТА: АНТИФРОД (модели выявления мошенничества / подозрительных операций).

Цель датасета: бинарная/мультиклассовая классификация события как fraud / не fraud (или уровень риска).
Учитывай сильный дисбаланс классов: не предлагай массовое удаление строк по выбросам в сумме/частоте без явной связи с таргетом.
Ищи потенциальные УТЕЧКИ: признаки из будущего (метки расследования, статус блокировки после события), агрегаты по всей истории клиента без временной отсечки.
Дубликаты: часто transaction_id / operation_id / payment_id — используй dedupe subset по бизнес-ключу, если колонки есть.
Временные поля: собери datetime, проверь монотонность и часовые пояса в validation_notes; предложи приведение к datetime64[ns].
Признаки скорости (velocity): если есть user/device/card/account и timestamps — отметь в binning_notes идеи rolling/count за окна (без реализации — только что проверить типы и NA).
Категории: канал, MCC, тип устройства, гео — strip_whitespace, mode/UNKNOWN для пропусков, без удаления редких категорий без причины.
Числовые суммы/лимиты: аккуратный winsorize_iqr только если явные выбросы; иначе numeric_outliers: null.
Целевая переменная: не удаляй и не заполняй цель (fraud_flag / is_fraud / target и т.п.) — только пометь в validation_notes.
В summary_ru кратко опиши риски утечек и стратегию выборки по времени (если есть даты).
""",
        FilePreset.legal_entity_scoring: """
КОНТЕКСТ ПРЕСЕТА: СКОРИНГ ЮРИДИЧЕСКИХ ЛИЦ (PD / рейтинг контрагента / лимиты).

Цель: оценка надёжности/риска компании; типично classification или regression по дефолту/просрочке/рейтингу.
Идентификатор: ИНН/ОГРН/contract_id — dedupe subset по ключу юрлица + отчётной дате (если есть период снимка).
Отчётность: выручка, активы, обязательства, EBITDA — проверь знак, порядок величин, отсутствие смешения тысяч/миллионов (validation_notes).
Отрасль (ОКВЭД), регион, форма собственности — категории: strip, пропуски → mode или константа «UNKNOWN».
Малый бизнес vs крупный: не удаляй выбросы по выручке вслепую; используй winsorize_iqr только для явно ошибочных значений.
Даты регистрации, год учреждения — datetime или int year с проверкой диапазона.
Фичи «из будущего» относительно даты решения — явно предупреди в validation_notes (lookup leakage).
Биннинг: возраст компании, размер бизнеса, коэффициенты — только если есть непрерывные числовые колонки и это улучшает монотонность; суффикс _binned.
В summary_ru укажи предполагаемую точку принятия решения (as-of дата) если видно по колонкам.
""",
        FilePreset.individual_scoring: """
КОНТЕКСТ ПРЕСЕТА: СКОРИНГ ФИЗИЧЕСКИХ ЛИЦ (retail / кредитная заявка / PD физлица).

Цель: одобрение/лимит/вероятность дефолта; соблюдай комплаенс: не предлагай использовать прямые запрещённые признаки (раса, религия и т.д.) —
если такие колонки есть — только validation_notes «исключить из модели», не включай в fill_na как полезные.
Идентификатор заявки/клиента + дата заявки — dedupe по связке, если это снимок на дату.
Возраст: проверь диапазон 18–90+, монотонность; при необходимости clip в numeric_clip.
Доход, платежи, долговая нагрузка: типы float, пропуски — median/mean только где уместно; для категориальных источников дохода — mode.
Бюро/внутренние скоры: не смешивать шкалы; проверить NA и коды «нет данных» (-1, 999) — описать в validation_notes и предложить замену или отдельную категорию.
Телефоны/адреса как текст — strip_whitespace; хэши если есть — string/category.
Биннинг: возраст, стаж, суммы — quantile или equal по смыслу равномерности PD; не перебиннить целевую переменную.
Цель (default_flag / target): не трогать пропуски цели кроме как drop_rows в крайнем случае — отразить в cleaning_notes.
""",
        FilePreset.credit_transition_matrix: """
КОНТЕКСТ ПРЕСЕТА: КОРЗИНА TR («Денежный 1») + МАКРОФАКТОРЫ (Казахстан, квартальные ряды).

ТИПИЧНЫЙ ВВОД (как у пользователя):
A) Лист/файл МАКРО: период 2010Q1…2022Q4 в первом столбце; колонки real_gdp, GDD_Min_R, GDD_Elc_R,
   GDD_Con_R, GDD_Trd_R, GDD_Trn_R (млрд тенге, цены 2005 г.; в файле — запятая как десятичный разделитель).
B) Лист/файл TR (таргет): «Денежный 1», период 2017Q1…2022Q4; 9 колонок долей перехода в %:
   1>1, 1>2, 1>3, 2>1, 2>2, 2>3, 3>1, 3>2, 3>3 (сумма по строке для каждого «from» ≈ 100).
Excel с двумя листами склеивается по кварталу (inner join на пересечении 2017Q1–2022Q4).

ОБЯЗАТЕЛЬНО transition_matrix в JSON:
- product_label: "Денежный 1"
- bucket_column: "basket_tr" (или null — константа в данных)
- period_column: "period"
- macro_columns: ["real_gdp","GDD_Min_R","GDD_Elc_R","GDD_Con_R","GDD_Trd_R","GDD_Trn_R"]
- transition_rate_columns: ["1>1","1>2","1>3","2>1","2>2","2>3","3>1","3>2","3>3"]
- dependent_column: один из TR-колонок для краткого adj. R² (напр. "2>1") или null — тогда считаются все 9
- transform_macro: true, transform_targets: true
- feature_transforms: для каждого макро и каждого 1>j — ["qoq_abs","qoq_rel","log","zscore"]

Сервис считает: ADF, KPSS, PP; VIF по макро; adj. R² каждого 1>j к макро; нормальность; лаги PACF/ACF.

validation_notes: доли TR в [0,100]; суммы 1>1+1>2+1>3 и 2>*, 3>* ≈ 100; макро только ≥0 для log.
cleaning: dedupe по period; strip_whitespace; fill_na для макро — осторожно; numeric_outliers: null.
binning: [] (корзины 1/2/3 уже дискретны).
econometric_notes: нестационарность ВВП/РВДС; VIF между секторами; какие лаги макро для 2>1 и т.д.
summary_ru: продукт TR, окно 2017Q1–2022Q4 после join с макро с 2010Q1.
""",
    }
    return blocks[preset].strip()
